// Group dafim by perek
export function getDafimByPerek(): Perek[] {
  const perekMap = new Map<number, Perek>();

  for (const daf of allDafim) {
    if (!perekMap.has(daf.perekNumber)) {
      perekMap.set(daf.perekNumber, {
        number: daf.perekNumber,
        name: daf.perekName,
        nameHebrew: daf.perekNameHebrew,
        dafim: [],
      });
    }
    perekMap.get(daf.perekNumber)!.dafim.push(daf);
  }

  return Array.from(perekMap.values()).sort((a, b) => a.number - b.number);
}

export function getAllDafim(): Daf[] {
  return allDafim;
}

export function getDafBySiman(siman: string): Daf | undefined {
  return allDafim.find((d) => d.siman.toLowerCase() === siman.toLowerCase());
}

export function getDafByNumber(num: number): Daf | undefined {
  return allDafim.find((d) => d.dafNumber === num);
}

